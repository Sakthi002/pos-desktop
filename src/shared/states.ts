  INDIAN_STATES.find((s) => s.code === code);

/**
 * A GSTIN embeds its state code as the first two characters. Used to warn when
 * the entered GSTIN disagrees with the selected state.
 */
export const stateCodeFromGstin = (gstin: string): string | null =>
  /^\d{2}/.test(gstin) ? gstin.slice(0, 2) : null;
